"""Finish generated character sheets; all writes stay in art-v3/delivery.

Source artwork is generated by imagegen. This script only cleans alpha, crops,
calibrates the generated palette and exports the user-specified pixel anchors.
"""
from pathlib import Path
import json, sys, hashlib
import numpy as np
import cv2
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / 'character-prompts.json'
STATES = ['idle', 'attack', 'spent', 'projectile']

def metadata(path):
    im = Image.open(path)
    a = np.array(im.getchannel('A'))
    return dict(path=str(path.resolve()), size=list(im.size), mode=im.mode,
                sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
                alpha_bbox=im.getchannel('A').getbbox(),
                transparent_pixels=int((a == 0).sum()))

def resize(im, wh):
    return im.convert('RGBa').resize(wh, Image.Resampling.LANCZOS).convert('RGBA')

def clean_cell(im, keep_detached=True):
    arr = np.array(im.convert('RGBA'))
    alpha = arr[:, :, 3]
    # Keep significant connected artwork, including a detached sweat droplet.
    core = (alpha > 100).astype('uint8')
    n, labels, stats, centers = cv2.connectedComponentsWithStats(core, 8)
    if n < 2:
        raise ValueError('No visible artwork')
    biggest = stats[1:, cv2.CC_STAT_AREA].max()
    ids = [i for i in range(1, n) if stats[i, cv2.CC_STAT_AREA] >= max(30, biggest * .0015)]
    if not keep_detached:
        ids = [1+int(np.argmax(stats[1:,cv2.CC_STAT_AREA]))]
    mask = np.isin(labels, ids).astype('uint8') * 255
    # Gate by a softly expanded contour, preserving the source alpha inside.
    mask = cv2.dilate(mask, np.ones((3, 3), np.uint8))
    mask = cv2.GaussianBlur(mask, (3, 3), .6)
    arr[:, :, 3] = np.minimum(alpha, mask)
    arr[:, :, 3][arr[:, :, 3] < 6] = 0
    arr[arr[:, :, 3] == 0] = 0
    out = Image.fromarray(arr)
    box = out.getchannel('A').getbbox()
    return out.crop(box), list(box)

def color_finish(im, hx, name, state):
    a = np.array(im); rgb = a[:, :, :3].copy()
    f = rgb.astype('float32') / 255
    target = np.array([int(hx[i:i+2],16) for i in (0,2,4)], dtype='float32')
    hsv = cv2.cvtColor(rgb, cv2.COLOR_RGB2HSV).astype(float)
    target_hsv = cv2.cvtColor(target.astype('uint8').reshape(1,1,3), cv2.COLOR_RGB2HSV)[0,0]
    opaque = a[:,:,3] > 230
    dist = cv2.distanceTransform(opaque.astype('uint8'), cv2.DIST_L2, 5)
    if name not in ('white', 'charcoal'):
        dh = abs(hsv[:,:,0] - float(target_hsv[0])); dh = np.minimum(dh,180-dh)
        mask = opaque & (dist > 1.3) & (dh < 19) & (hsv[:,:,1] > 80) & (hsv[:,:,2] > 90)
        # Small colored iris islands are face details, not body color.
        n, lab, stats, _ = cv2.connectedComponentsWithStats(mask.astype('uint8'),8)
        keep = [i for i in range(1,n) if stats[i,cv2.CC_STAT_AREA] > max(32,mask.sum()*.012)]
        mask = np.isin(lab,keep)
        labs = cv2.cvtColor(f,cv2.COLOR_RGB2LAB)
        target_lab = cv2.cvtColor((target/255).reshape(1,1,3),cv2.COLOR_RGB2LAB)[0,0]
        anchor = np.percentile(labs[mask],55,axis=0)
        contrast=[.45,.25,.25] if name=='blue' and state=='spent' else [.72,.34,.34]
        new_lab = target_lab+(labs-anchor)*np.array(contrast,dtype='float32')
        new = np.clip(cv2.cvtColor(new_lab.astype('float32'),cv2.COLOR_LAB2RGB)*255,0,255)
        a[:,:,:3][mask] = np.rint(new[mask]).astype('uint8')
    elif name == 'white':
        mask=opaque & (rgb.min(2)>200) & (rgb.max(2).astype(int)-rgb.min(2)<40)
        # Cool neutral body; keep gray contours, eyes and mouth intact.
        v=np.clip(rgb.mean(2)+6,0,255)
        new=np.stack([v-1,v,v+2],axis=2).clip(0,255)
        a[:,:,:3][mask]=np.rint(new[mask]).astype('uint8')
    else:
        mask=opaque & (rgb.max(2)<115) & (rgb.min(2)>22) & (dist>1.3)
        v=rgb.mean(2); anchor=np.percentile(v[mask],55)
        v=np.clip(45+(v-anchor)*.72,0,255)
        a[:,:,:3][mask]=np.repeat(v[:,:,None],3,2)[mask].round().astype('uint8')
    if state == 'spent':
        a[:,:,:3][mask] = np.rint(a[:,:,:3][mask].astype(float)*.97).astype('uint8')
    a[a[:,:,3]==0]=0
    return Image.fromarray(a), mask

def hollow_bubble(im,hx):
    # Preserve generated rim/highlight pixels; remove unwanted opaque filling.
    im=resize(im,(58,58)); a=np.array(im)
    if hx=='FFFFFF':
        value=a[:,:,:3].mean(2)
        a[:,:,:3]=np.stack([value,value+1,value+3],2).clip(0,255).round().astype('uint8')
    yy,xx=np.mgrid[:58,:58];r=np.sqrt(((xx-28.5)/28.5)**2+((yy-28.5)/28.5)**2)
    fade=np.clip((r-.72)/.17,0,1)
    a[:,:,3]=np.rint(a[:,:,3]*fade).astype('uint8')
    a[:,:,3][a[:,:,3]<5]=0;a[a[:,:,3]==0]=0
    out=Image.new('RGBA',(64,64));out.alpha_composite(Image.fromarray(a),(3,3))
    return out

def process(item,attempt):
    src=next(a for a in item['attempts'] if a['attempt']==attempt)
    im=Image.open(src['archive_path']).convert('RGBA'); w,h=im.size
    # Generated cells sometimes spill a floppy ear past a nominal quarter.
    # Divide in actual empty gaps between the four largest connected subjects.
    alpha=np.array(im)[:,:,3]
    _,_,stats,_=cv2.connectedComponentsWithStats((alpha>100).astype('uint8'),8)
    ids=sorted(range(1,len(stats)),key=lambda i:stats[i,4],reverse=True)[:4]
    subjects=sorted([stats[i] for i in ids],key=lambda s:s[0]+s[2]/2)
    cuts=[0]+[round((subjects[k][0]+subjects[k][2]+subjects[k+1][0])/2) for k in range(3)]+[w]
    cells=[]; boxes=[]
    for k in range(4):
        c,box=clean_cell(im.crop((cuts[k],0,cuts[k+1],h)),keep_detached=k<3)
        cells.append(c);boxes.append(box)
    scale=min(148/max(c.height for c in cells[:3]),178/max(c.width for c in cells[:3]))
    sizes=[(2*round(c.width*scale/2),round(c.height*scale)) for c in cells[:3]]
    if min(s[1] for s in sizes)<120:
        raise ValueError(f'{item["character"]}: cannot fit common scale into 120–150 px: {sizes}')
    dest=ROOT/'creatures'/item['character']/item['hex'];dest.mkdir(parents=True,exist_ok=True)
    outputs=[]
    for k,state in enumerate(STATES):
        if k<3:
            c=resize(cells[k],sizes[k]);c,mask=color_finish(c,item['hex'],item['character'],state)
            # Even occupied width provides an exact x=112 center at pixel boundaries.
            cw,ch=c.size
            if cw%2:
                padded=Image.new('RGBA',(cw+1,ch));padded.alpha_composite(c,(0,0));c=padded
            out=Image.new('RGBA',(224,256));x=112-c.width//2;y=212-c.height
            out.alpha_composite(c,(x,y))
            fullmask=Image.new('L',(224,256));fullmask.paste(Image.fromarray(mask.astype('uint8')*255),(x,y))
            mpath=ROOT/'_qa'/f'mask-{item["character"]}-{state}.png';fullmask.save(mpath)
        else:
            out=hollow_bubble(cells[k],item['hex'])
        path=dest/(state+'.png');out.save(path)
        outputs.append(dict(state=state,**metadata(path)))
    item['selected_attempt']=attempt;item['outputs']=outputs
    item['processing']={'source_cell_boxes':boxes,'shared_scale':scale,'three_state_sizes':sizes,
        'anchor':'x=112; bottom pixel boundary y=212, pixels y>=212 transparent',
        'methods':['source alpha preserved inside cleaned silhouette','premultiplied-alpha resize using one scale for all three poses','CIELAB palette calibration preserving volume, face and highlights','generated bubble center alpha cleared; generated rim retained']}
    return outputs

def preview(items):
    made=[a for a in items if a.get('outputs')]
    canvas=Image.new('RGB',(1080,285*len(made)),(238,241,245));d=ImageDraw.Draw(canvas)
    for row,a in enumerate(made):
        y=row*285;d.text((12,y+8),f'{a["id"]}: {a["character"]} #{a["hex"]}',fill=(32,45,66))
        for k,o in enumerate(a['outputs']):
            im=Image.open(o['path']);x=22+k*256
            if k==3:
                # Both checker and dark panels expose alpha filling problems.
                for yy in range(y+70,y+214,12):
                    for xx in range(x,x+192,12):
                        d.rectangle((xx,yy,xx+11,yy+11),fill=(210,215,221) if ((xx-x)//12+(yy-y-70)//12)%2 else (246,248,251))
                im=im.resize((128,128),Image.Resampling.NEAREST);canvas.paste(im,(x+32,y+78),im)
            else:
                canvas.paste(im,(x,y+20),im)
                d.line((x,y+232,x+224,y+232),fill=(175,186,198))
            d.text((x+70,y+263),o['state'],fill=(45,55,75))
    path=ROOT/'_qa/characters-contact-sheet.png';canvas.save(path);return path

if __name__=='__main__':
    m=json.loads(MANIFEST.read_text())
    if len(sys.argv)>1:
        item=next(a for a in m['items'] if a['id']==int(sys.argv[1]));process(item,int(sys.argv[2]))
        MANIFEST.write_text(json.dumps(m,ensure_ascii=False,indent=2)+'\n')
        print(json.dumps({'id':item['id'],'processing':item['processing'],'outputs':item['outputs']},ensure_ascii=False))
