        public float Gap // f54987: use < tests to preserve source NaN behavior.
        {
            get
            {
                float front = frontGridY;
                if (front < 0f) return 999f;
                front  =                 OriginalMath.Binary32(front+(Offset));
                return front < 0f ? 999f : OriginalMath.Binary32(562f - front);
            }
        }

        // f55049; f53959 is shared only by these two color predicates here.
        // In-flight targets remain reserved; their eventual hit still resolves.
        public bool Sweep(int color)
        {
            if (!Active || color < 0 || ActiveFinale != null || color >= ColorCount) return false;
            int count = 0;
            for (int cell = 0; cell < Alive.Length; cell++)
            {
                if (!Alive[cell] || reserved[cell] || ColorAt(cell) != color) continue;
                Alive[cell] = false;
                int slot = position[cell];
                if (slot >= 0) sand[slot] = -1;
                count = unchecked(count + 1);
            }
            if (count == 0) return false;
            Fleet.RemoveAll(f => f.Color == color);
            foreach (List<Fighter> lane in Reserve) lane.RemoveAll(f => f.Color == color);
            sandDirty = true;
            Remaining = unchecked(Remaining - count);
            Score = unchecked(Score + count * 10);
            RefreshFronts();
            Swept?.Invoke(color, count);
            Cue?.Invoke("blast");
            NoticeTime = 2.4f; Notice = "同色清屏，击碎" + count + "只怪物";
            if (Remaining == 0) { State = Phase.Won; Cue?.Invoke("win"); }
            return true;
        }

        // f55097. Original diagnostic fixture: fill available bays, empty all
        // reserve/incoming queues, and retain up to keep matching on-board cells.
        // No score/cue/reward is generated by cells removed here.
        public int StageFinaleForEvidence(int keep)
        {
            if (!Active || ActiveFinale != null) return Remaining;
            for (int lane = 0; lane < Reserve.Length; lane++)
                while (Reserve[lane].Count > 0 && Fleet.Count < UnlockedSlots)
                    if (!DeployAt(lane, 0)) break;
            foreach (List<Fighter> lane in Reserve) lane.Clear();
            var colors = new HashSet<int>();
            foreach (Fighter fighter in Fleet) colors.Add(fighter.Color);
            var candidates = new List<int>();
            for (int cell = 0; cell < Alive.Length; cell++)
                if (Alive[cell] && cell < position.Length && position[cell] >= 0 && !reserved[cell]
                    && colors.Contains(cell < boardCount ? Level.cells[cell] : Level.stream[cell - boardCount]))
                    candidates.Add(cell);
            // f55135: compare descending screen Y, including Offset in both
            // operands. Do not cancel it: binary32 rounding changes comparisons.
            // f55097 -> f5656 and its original ArraySortHelper: equal-Y ordering
            // affects which cells survive the keep boundary. Use the translated
            // helper already shared by rocket and weapon selection.
            OriginalSort.Sort(candidates, (a, b) => (OriginalMath.Binary32(y[b] + Offset)).CompareTo(OriginalMath.Binary32(Offset + y[a])));
            var retained = new HashSet<int>();
            for (int i = 0; i < Math.Min(keep, candidates.Count); i++) retained.Add(candidates[i]);
            for (int cell = 0; cell < Alive.Length; cell++)
            {
                if (!Alive[cell] || reserved[cell] || retained.Contains(cell)) continue;
                Alive[cell] = false;
                int slot = position[cell];
                if (slot >= 0) sand[slot] = -1;
                Remaining = unchecked(Remaining - 1);
            }
            foreach (Queue<int> queue in incoming) queue.Clear();
            sandDirty = true;
            RefreshFronts();
            return Remaining;
        }
    }
